"""Classify exact content repeated within repositories containing CLAUDE.md.

The analysis unit is first a unique SHA-256 content identity, classified once,
and then each repository-local duplicate group.  Results are aggregated by
unique content, repository group, participating file, repeated instance, and
repository.  SQLite is opened read-only and immutable.

Example:

    python scripts/claude_repeated_content_classes.py \\
        --db mined.db \\
        --classes-output article/claude_repeated_content_classes.csv \\
        --groups-output article/claude_repeated_content_groups.csv \\
        --members-output article/claude_repeated_content_members.csv \\
        --audit-output article/claude_repeated_content_audit.csv \\
        --summary-output article/claude_repeated_content_summary.json
"""
